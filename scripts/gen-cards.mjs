// Generates src/game/cards.ts from mechanics/powers.txt + rarity.txt + name_fac_background.txt
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mech = (f) => readFileSync(join(root, 'mechanics', f), 'utf8');

// --- powers.txt: | NNNN | Name | Pwr | text |
const powers = new Map();
for (const line of mech('powers.txt').split('\n')) {
  const m = line.match(/^\|\s*(\d{4})\s*\|\s*(.+?)\s*\|\s*(\d+)\s*\|\s*(.+?)\s*\|/);
  if (m) powers.set(m[1], { name: m[2].trim(), power: +m[3], text: m[4].trim() });
}

// --- rarity.txt: NNNN - Name: Rarity
const rarity = new Map();
for (const m of mech('rarity.txt').matchAll(/(\d{4})\s*-\s*[^:\n]+:\s*(Mortal|Cursed|Arcane|Forbidden|Mythic|Relic|Divine)/gi)) {
  rarity.set(m[1], m[2].toLowerCase());
}

// --- name_fac_background.txt: NNNN - Name \n Faction: X | Type: Monster
const faction = new Map();
const bg = mech('name_fac_background.txt');
const blocks = bg.split(/(?=^\d{4}\s*-)/m);
for (const b of blocks) {
  const hm = b.match(/^(\d{4})\s*-/);
  if (!hm) continue;
  const fm = b.match(/Faction:\s*(\w+)/i) || b.match(/Type:\s*(\w+)/i);
  faction.set(hm[1], fm ? fm[1].toLowerCase() : 'unknown');
}
const facMap = {
  elarion: 'elarion', elderveld: 'elderveld', kalthrone: 'kalthrone',
  hochreich: 'hochreich', ravaria: 'ravaria', varkazan: 'varkazan',
  varkhazan: 'varkazan', monster: 'monster', hotc: 'hotc', unknown: 'unknown',
};

function kindOf(text) {
  const t = text.toLowerCase();
  if (t.startsWith('chaos')) return 'chaos';
  if (t.startsWith('spy')) return 'spy';
  if (t.startsWith('on reveal')) return 'onReveal';
  if (t.startsWith('ongoing')) return 'ongoing';
  if (t.startsWith('medic')) return 'medic';
  if (t.startsWith('muster')) return 'muster';
  if (t.startsWith('move')) return 'move';
  if (t.startsWith('faction bond')) return 'factionBond';
  if (t.startsWith('hero')) return 'hero';
  if (t.startsWith('relic')) return 'ongoing';
  return 'none';
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

let out = `import type { CardDef } from './types';

// AUTO-GENERATED by scripts/gen-cards.mjs from mechanics/*.txt — do not hand-edit.
// Token defs (summon-only) are appended after the 214-card pool.
export const CARDS: CardDef[] = [
`;

const ids = [...powers.keys()].sort();
for (const id of ids) {
  const p = powers.get(id);
  const r = rarity.get(id) ?? 'mortal';
  const f = facMap[faction.get(id) ?? 'unknown'] ?? 'unknown';
  const k = kindOf(p.text);
  out += `  { id: '${id}', name: '${esc(p.name)}', power: ${p.power}, faction: '${f}', rarity: '${r}', kind: '${k}', text: '${esc(p.text)}', art: '/cards/${id}.png' },\n`;
}

out += `];

// Summon-only tokens (not in the deck pool).
export const TOKENS: CardDef[] = [
  { id: 't-blobeye', name: 'Blobeye', power: 2, faction: 'monster', rarity: 'cursed', kind: 'none', text: 'No Ability.', art: '/cards/0214.png', token: true },
  { id: 't-beetle', name: 'Beetle', power: 1, faction: 'monster', rarity: 'mortal', kind: 'none', text: 'No Ability.', art: '/cards/0005.png', token: true },
  { id: 't-elemental', name: 'Elemental', power: 5, faction: 'monster', rarity: 'arcane', kind: 'none', text: 'No Ability.', art: '/cards/0161.png', token: true },
  { id: 't-flame-demon', name: 'Flame Demon', power: 2, faction: 'monster', rarity: 'cursed', kind: 'none', text: 'No Ability.', art: '/cards/0189.png', token: true },
  { id: 't-werewolf', name: 'Werewolf', power: 3, faction: 'monster', rarity: 'cursed', kind: 'none', text: 'No Ability.', art: '/cards/0046.png', token: true },
  { id: 't-divine-dragon', name: 'Divine Dragon', power: 10, faction: 'monster', rarity: 'divine', kind: 'none', text: 'No Ability.', art: '/cards/0201.png', token: true },
  { id: 't-monster', name: 'Monster', power: 6, faction: 'monster', rarity: 'cursed', kind: 'none', text: 'No Ability.', art: '/cards/0167.png', token: true },
];

export const CARD_BY_ID = new Map<string, CardDef>([...CARDS, ...TOKENS].map((c) => [c.id, c]));
`;

writeFileSync(join(root, 'src', 'game', 'cards.ts'), out);
console.log(`Wrote ${ids.length} cards + 7 tokens`);
const missing = ids.filter((i) => !rarity.has(i));
if (missing.length) console.log('Missing rarity (defaulted mortal):', missing.join(', '));
