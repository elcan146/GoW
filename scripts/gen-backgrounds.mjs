// Parses mechanics/name_fac_background.txt into src/game/backgrounds.ts
// Entry format:
//   0001 - Maneater
//   Type: Monster | Faction: <name>
//
//   Background: <single line of lore text>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'mechanics', 'name_fac_background.txt'), 'utf8');

const backgrounds = {};
let currentId = null;

for (const line of src.split(/\r?\n/)) {
  const header = line.match(/^(\d{4})\s*-\s*(.+)$/);
  if (header) {
    currentId = header[1];
    continue;
  }
  const bg = line.match(/^Background:\s*(.+)$/);
  if (bg && currentId) {
    backgrounds[currentId] = bg[1].replace(/\s+/g, ' ').trim();
    currentId = null;
  }
}

const entries = Object.entries(backgrounds)
  .map(([id, text]) => `  '${id}': ${JSON.stringify(text)},`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/gen-backgrounds.mjs from mechanics/name_fac_background.txt — do not hand-edit.
export const BACKGROUNDS: Record<string, string> = {
${entries}
};
`;

fs.writeFileSync(path.join(root, 'src', 'game', 'backgrounds.ts'), out);
console.log(`Wrote ${Object.keys(backgrounds).length} backgrounds`);
