// Generates src/game/cards.ts + src/game/backgrounds.ts from data/cards.json.
// Also validates that card art exists in assets/cards and that effect types
// are known. Re-run after editing cards.json:
//   node scripts/gen-cards.mjs        (or: npm run gen:cards)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(root, 'data/cards.json'), 'utf8'));

const KINDS = new Set(['none', 'onReveal', 'ongoing', 'chaos', 'spy', 'medic', 'muster', 'move', 'factionBond', 'hero']);
const FACTIONS = new Set(['elarion', 'elderveld', 'kalthrone', 'hotc', 'hochreich', 'ravaria', 'varkazan', 'monster', 'unknown']);
const RARITIES = new Set(['mortal', 'cursed', 'arcane', 'forbidden', 'mythic', 'relic', 'divine']);
const EFFECT_TYPES = new Set([
  'auraAllHere', 'auraFriendlyHere', 'auraFactionHere', 'auraKindHere',
  'auraFactionGlobal', 'auraKindGlobal', 'auraNameMatch', 'auraAdjacent',
  'doubleAuras', 'selfPerHand', 'selfPerFaction', 'protect', 'hideCards',
  'debuffOnEnemyPlay', 'buffOnFriendlyPlay', 'blockEnemyOnReveal',
  'doubleOnReveal', 'buffDrawn', 'buffHand', 'growPerTurn',
  'moveRandomEachTurn', 'moveOnceAdjacent', 'pullFriendly', 'moveRandomEnemy',
  'trapOnEnemyMove', 'spyDrawSteal', 'spyDraw', 'spyCopyLast', 'spyRevealHand',
  'resurrect', 'resurrectEnemy', 'sacrificeResurrect', 'muster',
  'destroyHighestIfTotal', 'debuffAllEnemies', 'silenceOngoingHere',
  'repeatOnReveal', 'destroyLowest', 'destroyRandom', 'draw', 'silenceNext',
  'copyEnemyPlayedHere', 'resurrectAll', 'summon', 'buffKindHere',
  'destroyBelow', 'sacrificeLowestDraw', 'moveRandomEnemyAdjacent',
  'silenceAllEnemies', 'copyOngoing', 'stealOngoing', 'stealPowerAll',
  'devour', 'chaos', 'factionBond', 'hero', 'none',
]);

const artDir = join(root, 'assets/cards');
const artFiles = new Set(
  existsSync(artDir) ? readdirSync(artDir).map((f) => f.replace(/\.[^.]+$/, '')) : [],
);

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const escDq = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');

const warnings = [];
const seen = new Set();

function check(c) {
  if (seen.has(c.id)) warnings.push(`${c.id}: duplicate id`);
  seen.add(c.id);
  if (!KINDS.has(c.kind)) warnings.push(`${c.id}: unknown kind '${c.kind}'`);
  if (!FACTIONS.has(c.faction)) warnings.push(`${c.id}: unknown faction '${c.faction}'`);
  if (!RARITIES.has(c.rarity)) warnings.push(`${c.id}: unknown rarity '${c.rarity}'`);
  if (c.effect && !EFFECT_TYPES.has(c.effect.type))
    warnings.push(`${c.id}: unknown effect type '${c.effect.type}'`);
  const artKey = String(c.art ?? '').replace(/^.*\//, '').replace(/\.[^.]+$/, '');
  if (artKey && !artFiles.has(artKey))
    warnings.push(`${c.id}: art '${c.art}' — no image in assets/cards (run gen:assets after adding)`);
}

for (const c of [...data.cards, ...data.tokens]) check(c);

// --- cards.ts -----------------------------------------------------------------
const fx = (e) => (e ? `, effect: ${JSON.stringify(e)}` : '');
let out = `import type { CardDef } from './types';

// AUTO-GENERATED by scripts/gen-cards.mjs from data/cards.json — do not hand-edit.
// Edit data/cards.json (or use scripts/card_editor.py) and re-run the generator.
export const CARDS: CardDef[] = [
`;
for (const c of data.cards) {
  out += `  { id: '${c.id}', name: '${esc(c.name)}', power: ${c.power}, faction: '${c.faction}', rarity: '${c.rarity}', kind: '${c.kind}', text: '${esc(c.text)}', art: '${esc(c.art)}'${fx(c.effect)} },\n`;
}
out += `];

// Summon-only tokens (not in the deck pool).
export const TOKENS: CardDef[] = [
`;
for (const c of data.tokens) {
  out += `  { id: '${c.id}', name: '${esc(c.name)}', power: ${c.power}, faction: '${c.faction}', rarity: '${c.rarity}', kind: '${c.kind}', text: '${esc(c.text)}', art: '${esc(c.art)}'${fx(c.effect)}, token: true },\n`;
}
out += `];

export const CARD_BY_ID = new Map<string, CardDef>([...CARDS, ...TOKENS].map((c) => [c.id, c]));
`;
writeFileSync(join(root, 'src/game/cards.ts'), out, 'utf8');

// --- backgrounds.ts -------------------------------------------------------------
let bg = `// AUTO-GENERATED by scripts/gen-cards.mjs from data/cards.json — do not hand-edit.
export const BACKGROUNDS: Record<string, string> = {
`;
for (const c of data.cards) {
  if (c.background) bg += `  '${c.id}': "${escDq(c.background)}",\n`;
}
bg += '};\n';
writeFileSync(join(root, 'src/game/backgrounds.ts'), bg, 'utf8');

console.log(`cards.ts: ${data.cards.length} cards + ${data.tokens.length} tokens; backgrounds.ts: ${data.cards.filter((c) => c.background).length} entries`);
if (warnings.length) {
  console.log('\nWARNINGS:');
  for (const w of warnings) console.log('  ' + w);
}
