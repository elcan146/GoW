// Generates src/assets.ts — static require() manifest for Metro bundler.
// Metro needs literal require() calls, so every bundled asset is listed here.
// Re-run after adding/removing files in ../assets:  node scripts/gen-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const assets = path.join(root, '..', 'assets');
const out = path.join(root, '..', 'src', 'assets.ts');

const req = (rel) => `require('../assets/${rel}')`;
const list = (dir, re) =>
  fs.existsSync(path.join(assets, dir))
    ? fs.readdirSync(path.join(assets, dir)).filter((f) => re.test(f)).sort()
    : [];

const L = [];
L.push('// AUTO-GENERATED by scripts/gen-assets.mjs — do not hand-edit.');
L.push("import type { ImageSourcePropType } from 'react-native';");
L.push('');

// ---- card faces -----------------------------------------------------------
const cards = list('cards', /\.(png|jpe?g|webp)$/i);
L.push('const CARD_IMAGES: Record<string, ImageSourcePropType> = {');
for (const f of cards) L.push(`  '${f.replace(/\.[^.]+$/, '')}': ${req(`cards/${f}`)},`);
L.push('};');
L.push('');

// ---- card backs -----------------------------------------------------------
const backs = list('card_back', /\.(png|jpe?g|webp)$/i);
L.push('const CARD_BACKS: Record<string, ImageSourcePropType> = {');
for (const f of backs) L.push(`  '${f.replace(/\.[^.]+$/, '')}': ${req(`card_back/${f}`)},`);
L.push('};');
L.push('');

// ---- location art ---------------------------------------------------------
const locs = list('locations', /\.(png|jpe?g|webp)$/i);
L.push('const LOCATION_IMAGES: Record<string, ImageSourcePropType> = {');
for (const f of locs) L.push(`  '${f.replace(/\.[^.]+$/, '')}': ${req(`locations/${f}`)},`);
L.push('};');
L.push('');

// ---- sfx ------------------------------------------------------------------
const sfx = list('sfx', /\.(mp3|wav|ogg|m4a)$/i);
L.push('export const SFX_FILES: Record<string, number> = {');
for (const f of sfx) L.push(`  '${f}': ${req(`sfx/${f}`)},`);
L.push('};');
L.push('');

// ---- ost ------------------------------------------------------------------
const ost = list('ost', /\.(wav|mp3|ogg|m4a|flac)$/i);
const arts = list('ost/albumarts', /\.(png|jpe?g|webp)$/i);
L.push('export interface MusicTrack { name: string; src: number; art: ImageSourcePropType | null }');
L.push('export const MUSIC_FILES: MusicTrack[] = [');
for (const f of ost) {
  const base = f.replace(/\.[^.]+$/, '');
  const art = arts.find((a) => a.replace(/\.[^.]+$/, '') === base);
  L.push(`  { name: '${base.replace(/'/g, "\\'")}', src: ${req(`ost/${f}`)}, art: ${art ? req(`ost/albumarts/${art}`) : 'null'} },`);
}
L.push('];');
L.push('');

// ---- lookup helpers -------------------------------------------------------
L.push(`/** Card face image for a CardDef.art web path like '/cards/0001.png'. */`);
L.push('export function cardImage(art: string): ImageSourcePropType | undefined {');
L.push("  const key = art.replace(/^.*\\//, '').replace(/\\.[^.]+$/, '');");
L.push('  return CARD_IMAGES[key];');
L.push('}');
L.push('');
L.push('export function cardBack(faction: string): ImageSourcePropType | undefined {');
L.push("  return CARD_BACKS[faction + '_back'] ?? CARD_BACKS['unknown_back'];");
L.push('}');
L.push('');
L.push('// Filename prefixes in assets/locations (mirrors web locations.ts typos:');
L.push('// abbys, colesium). Suffix _1/_2/_3 = left/center/right board slot.');
L.push('const LOCATION_ART: Record<string, string> = {');
L.push("  abyss: 'abbys', battlefield: 'battlefield', coliseum: 'colesium',");
L.push("  'cursed-lands': 'cursedlands', 'dense-forest': 'denseforest', desert: 'desert',");
L.push("  dragons: 'dragons', elaria: 'Elaria', elderlands: 'Elderlands', future: 'future',");
L.push("  heaven: 'heaven', hell: 'hell', hochreich: 'hochreich', 'hotc-camp': 'hotc_camp',");
L.push("  intestines: 'intestines', kal: 'Kal', labyrinth: 'labyrinth', lava: 'lava',");
L.push("  mirror: 'mirror', plague: 'plague', plains: 'plains', random: 'random',");
L.push("  ravaria: 'Ravaria', shadowland: 'shadowland', snowy: 'snowy', soulland: 'soulland',");
L.push("  stakes: 'stakes', swamps: 'swamps', valhalla: 'valhalla', varkaz: 'Varkaz',");
L.push('};');
L.push('');
L.push('/** Art for a location at board slot index (0=left, 1=center, 2=right). */');
L.push('export function locationImage(locId: string, slotIndex: number): ImageSourcePropType | undefined {');
L.push('  const prefix = LOCATION_ART[locId] ?? locId;');
L.push('  return LOCATION_IMAGES[`${prefix}_${slotIndex + 1}`];');
L.push('}');
L.push('');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n'), 'utf8');
console.log(`assets.ts: ${cards.length} cards, ${backs.length} backs, ${locs.length} locations, ${sfx.length} sfx, ${ost.length} tracks`);
